"""Totality: what the package produces, the package must consume.

Every other test in this suite measures a function against inputs chosen
for it. This one measures the surface against inputs the *package itself*
produces, which is the question none of the others ask.

It exists because a defect once crossed eight formal properties, a ported
reference suite of 109 cases, an enumeration of the last column of all
thousand rows, full statement and branch coverage and four linters. All
of those measured the serialization format from inside, with inputs the
codec knew how to generate. None asked what the rest of the package emits
that the codec has to accept, and the answer was that ``compose`` emitted
a multi-quadrant index the codec refused.

Three things keep this from decaying into the hand-written list it exists
to replace. The census of the public surface is mechanical, and the
completeness of that census is itself an assertion, so a name added later
must land in a bucket or in a named exemption rather than slipping past.
The exemption for unimplemented stubs asserts that they still raise
:class:`NotImplementedError`, so it turns red on the day one of them is
implemented instead of quietly excusing a working function. And the
corpus is enumerated rather than sampled, with the size of every entry
declared, because a green table with no counts hides an empty bucket.
"""

from __future__ import annotations

import inspect
import sys
from typing import Any, Callable, Iterator

import pytest
from shapely.geometry import Polygon

import itacart
from itacart.exceptions import ITACaRTError

EMPTY = inspect.Parameter.empty

# --------------------------------------------------------------------------
# Mechanical census of the public surface
# --------------------------------------------------------------------------

#: First-parameter names that mean "an index or a cell arrives here".
_INDEX_PARAMETERS = frozenset({"index", "cell", "cells", "origin"})

#: Producers of indices and regions. The corpus comes from these, and none
#: of them may also stand in for the surface being measured: a corpus
#: generated by the consumer under test measures nothing.
PRODUCER_NAMES = (
    "compose",
    "normalize",
    "compact_cells",
    "polyfill",
    "get_children",
    "uncompact_cells",
    "geo_to_cell",
    "vertex_to_cell",
)

#: Names exempt because they are not implemented yet. Empty, and kept
#: rather than deleted: the census still routes through it, so a new stub
#: has somewhere to be declared and a test below still asserts that
#: whatever is named here really does raise. An exemption that has expired
#: is worth more standing at zero than removed, because removing it takes
#: the assertion with it.
UNIMPLEMENTED_STUBS: tuple[str, ...] = ()

#: Consumers that refuse the *environment* before they ever look at the
#: index. They stay in the census, because they are implemented and their
#: signature is real, but they are outside the escape sweep: the sweep asks
#: whether a produced index makes a consumer raise something the package
#: does not own, and a missing optional extra is not an answer to that
#: question. Leaving one in would make the sweep report thirty-five escapes
#: in an environment without the extra and none in an environment with it,
#: which measures pip rather than the surface.
#:
#: This is an assertion and not a licence, exactly like the stub exemption
#: above: ``test_the_optional_extra_exemption_is_earned`` blocks the import
#: and requires each name here to actually raise ``ImportError``, so a
#: function that stops needing the extra falls out of the exemption on the
#: day it stops needing it.
NEEDS_OPTIONAL_EXTRA = ("to_geodataframe",)

#: Second and later arguments for the consumers that require them. The
#: table's completeness is asserted, so a consumer that grows a required
#: argument fails here rather than being skipped.
EXTRA_ARGUMENTS: dict[str, tuple[Any, ...]] = {
    "are_neighbor_cells": ("NE(0001/0000)",),
    "cells_to_directed_edge": ("NE(0001/0000)",),
    "deflect": ("E",),
    "get_descendants": (2,),
    "get_neighbor": ("E",),
    "grid_distance": ("NE(0001/0000)",),
    "uncompact_cells": (2,),
}


def _public_callables() -> Iterator[tuple[str, Callable[..., Any]]]:
    for name in sorted(itacart.__all__):
        value = getattr(itacart, name)
        if callable(value):
            yield name, value


def _public_methods() -> Iterator[tuple[str, Callable[..., Any]]]:
    """Bound methods of the public classes, named ``Class.method``.

    The census classifies the names in ``__all__``, and a class enters it
    as one name. Its methods are a second surface that no sweep reached,
    which is how a facade method came to refuse a compositional index with
    a bare exception while the two functions refusing the identical
    argument shape used the package's own. The sweep now reaches them.

    The exception classes are skipped. What they expose is
    ``BaseException``'s surface and not this package's, and instantiating
    every one of them to sweep ``add_note`` would measure Python. So are the
    record types, for the same reason: ``DataVariable`` is a named tuple,
    whose public methods are the tuple's ``count`` and ``index``, and which
    cannot be built without its fields.
    """
    for name in sorted(itacart.__all__):
        value = getattr(itacart, name)
        if not isinstance(value, type) or issubclass(value, (BaseException, tuple)):
            continue
        instance = value()
        for attribute in sorted(dir(instance)):
            if attribute.startswith("_"):
                continue
            method = getattr(instance, attribute)
            if callable(method):
                yield f"{name}.{attribute}", method


def _first_parameter(function: Callable[..., Any]) -> str | None:
    try:
        parameters = list(inspect.signature(function).parameters.values())
    except (TypeError, ValueError):
        return None
    return parameters[0].name if parameters else None


def _required_extras(function: Callable[..., Any]) -> list[str]:
    try:
        parameters = list(inspect.signature(function).parameters.values())
    except (TypeError, ValueError):
        return []
    return [
        parameter.name
        for parameter in parameters[1:]
        if parameter.default is EMPTY
        and parameter.kind
        in (parameter.POSITIONAL_ONLY, parameter.POSITIONAL_OR_KEYWORD)
    ]


def _classify(name: str) -> set[str]:
    """Tag a public name. Every name must earn at least one tag."""
    tags: set[str] = set()
    if name in UNIMPLEMENTED_STUBS:
        tags.add("stub")
    value = getattr(itacart, name)
    if isinstance(value, type):
        tags.add("type")
    if name in PRODUCER_NAMES:
        tags.add("producer")
    if callable(value) and not isinstance(value, type):
        first = _first_parameter(value)
        if first in _INDEX_PARAMETERS:
            tags.add("consumer")
        elif first is not None:
            tags.add("other-signature")
        else:
            tags.add("no-arguments")
    if not callable(value):
        tags.add("constant")
    return tags


def _consumers() -> list[str]:
    functions = [
        name
        for name, _ in _public_callables()
        if "consumer" in _classify(name)
        and "stub" not in _classify(name)
        and name not in NEEDS_OPTIONAL_EXTRA
    ]
    methods = [
        name
        for name, method in _public_methods()
        if _first_parameter(method) in _INDEX_PARAMETERS
    ]
    return functions + methods


def test_the_census_classifies_every_public_name() -> None:
    """No name escapes the census in silence.

    This is the assertion that keeps the instrument from ageing into the
    hand-written list it replaces. A name added to the package must land
    in a bucket or in a named exemption; there is no third outcome.
    """
    unclassified = [name for name in itacart.__all__ if not _classify(name)]
    assert unclassified == [], f"unclassified public names: {unclassified}"


def test_the_census_reaches_the_whole_surface() -> None:
    """The buckets partition the surface, and the counts are declared."""
    tally: dict[str, int] = {}
    for name in itacart.__all__:
        for tag in _classify(name):
            tally[tag] = tally.get(tag, 0) + 1
    assert len(itacart.__all__) == 171, "surface changed; update the counts below"
    assert "stub" not in tally
    assert tally["type"] == 20
    assert tally["no-arguments"] == 4
    # Equality, not a floor. A floor lets the pin rot in both directions:
    # a consumer that quietly leaves the census still clears it, and so
    # does one that arrives without anyone deciding it belongs. Sixty-three
    # is the count of public names; the sweep below runs over sixty-four,
    # because the facade method the census reaches is not itself a name in
    # ``__all__``. Both are pinned, so a consumer leaving
    # either set fails here.
    assert tally["consumer"] == 63
    assert len(_consumers()) == 64
    assert tally["producer"] == len(PRODUCER_NAMES)


def test_the_coverage_exclusion_is_pinned_to_the_stubs_it_excuses() -> None:
    """No stub survives, and no exclusion excuses one.

    The exclusion for ``raise NotImplementedError`` was invisible in the
    coverage report: it shrank the denominator rather than showing a miss,
    so a new stub anywhere in the package would silently stop being
    measured. The count had to fall to zero as the stubs were implemented
    rather than be adjusted upward, and it has. Both halves are asserted
    here -- no such line in the package, and no such entry in the
    configuration -- because either one alone could return without the
    other noticing.

    The configuration is read by pulling the array out of the file text
    rather than by parsing it. A TOML parser is the obvious tool and is the
    wrong one: the only one in the standard library arrived in 3.11 and
    this package supports 3.10, so reaching for it buys a dependency to
    answer a question about a handful of string literals. A plain search of
    the file text is the wrong tool too, because the comment above the
    array explains why the entry was removed and so contains the very
    phrase being searched for. What is wanted is the array, so the array is
    what is read.
    """
    import pathlib
    import re

    root = pathlib.Path(itacart.__file__).parent
    counted = {
        path.name: path.read_text().count("raise NotImplementedError")
        for path in sorted(root.rglob("*.py"))
        if "raise NotImplementedError" in path.read_text()
    }
    assert counted == {}

    # Absent when the package is tested from an installed wheel rather than
    # from a source tree, which is the only case this guard covers.
    project = root.parent.parent / "pyproject.toml"
    if project.is_file():
        text = project.read_text(encoding="utf-8")
        opening = text.index("exclude_lines = [", text.index("[tool.coverage.report]"))
        array = text[opening : text.index("]", opening)]
        excluded = re.findall(r'"([^"]*)"', array)
        assert excluded, "exclude_lines was found but read as empty"
        assert "raise NotImplementedError" not in excluded


def test_the_stub_exemption_expires_by_itself() -> None:
    """Exempt names must still be unimplemented.

    An exemption that merely names functions goes stale the moment one of
    them starts working, and the surface silently stops being measured.
    Asserting that each still raises turns the exemption red on the day
    an implementation lands, which is the only way the isolation
    ends by construction rather than by someone remembering.
    """
    for name in UNIMPLEMENTED_STUBS:
        value = getattr(itacart, name)
        with pytest.raises(NotImplementedError):
            if isinstance(value, type):
                value()
            else:
                _call_with_anything(value)


def _call_with_anything(function: Callable[..., Any]) -> Any:
    """Call a stub with plausible arguments, since only the raise matters."""
    parameters = list(inspect.signature(function).parameters.values())
    required = [
        parameter
        for parameter in parameters
        if parameter.default is EMPTY
        and parameter.kind
        in (parameter.POSITIONAL_ONLY, parameter.POSITIONAL_OR_KEYWORD)
    ]
    return function(*(["NE(0001/0000)"] * len(required)))


def test_the_optional_extra_exemption_is_earned() -> None:
    """Every exempt name must genuinely fail without its optional extra.

    The exemption is measured rather than asserted from outside: the
    import of the extra is blocked and the function is called with an
    index the package itself produced, so the name earns its place by
    raising rather than by being listed. A function that grows a fallback
    and stops needing the extra fails here, which is how the exemption
    ends by construction instead of by someone remembering.
    """
    import builtins

    real_import = builtins.__import__

    def blocked(name: str, *args: Any, **kwargs: Any) -> Any:
        if name == "geopandas" or name.startswith("geopandas."):
            raise ImportError("blocked so the exemption has to be earned")
        return real_import(name, *args, **kwargs)

    produced = itacart.compose(["NE(0001/0001)", "NE(0002/0001)"])
    monkeypatched = sys.modules.pop("geopandas", None)
    builtins.__import__ = blocked
    try:
        for name in NEEDS_OPTIONAL_EXTRA:
            with pytest.raises(ImportError):
                _call(name, produced)
    finally:
        builtins.__import__ = real_import
        if monkeypatched is not None:
            sys.modules["geopandas"] = monkeypatched


def test_the_exempt_consumers_are_still_in_the_census() -> None:
    """Exemption from the sweep is not exemption from the census.

    The two are different questions and the distinction is easy to lose:
    a name dropped from the sweep for a good reason must still be
    classified, still counted, and still bound by the assertion that the
    buckets partition the surface.
    """
    for name in NEEDS_OPTIONAL_EXTRA:
        assert name in itacart.__all__
        assert "consumer" in _classify(name)
        assert "stub" not in _classify(name)
        assert name not in _consumers()


def test_the_extra_argument_table_covers_every_consumer_that_needs_one() -> None:
    """A consumer that grows a required argument fails here, not silently."""
    needing = {name for name in _consumers() if _required_extras(_resolve(name))}
    assert needing == set(EXTRA_ARGUMENTS), (
        f"missing from the table: {sorted(needing - set(EXTRA_ARGUMENTS))}; "
        f"stale in the table: {sorted(set(EXTRA_ARGUMENTS) - needing)}"
    )


# --------------------------------------------------------------------------
# The corpus, produced rather than written
# --------------------------------------------------------------------------


def _square(lon: float, lat: float, side: float) -> Polygon:
    return Polygon(
        [
            (lon, lat),
            (lon + side, lat),
            (lon + side, lat + side),
            (lon, lat + side),
        ]
    )


def _flatten(groups: Any) -> list[str]:
    out: list[str] = []
    for group in groups:
        out.extend(group if isinstance(group, list) else [group])
    return out


def _sample(cells: list[str], keep: int = 3) -> list[str]:
    """First, last and middle, so the sample is deterministic and small."""
    if len(cells) <= keep:
        return list(cells)
    return [cells[0], cells[len(cells) // 2], cells[-1]]


def _build_corpus() -> dict[str, list[str]]:
    """Every entry is here because something broke on it."""
    corpus: dict[str, list[str]] = {}

    # A cell set spanning two quadrants, which compose writes and the
    # serializer once refused.
    crossing = ["NE(0001/0001)", "NE(0002/0001)", "NW(0003/0004)"]
    corpus["compose over several quadrants"] = [itacart.compose(crossing)]

    # Regions over each boundary the fill has to survive.
    for label, polygon in (
        ("polyfill over the equator", _square(10.0, -0.02, 0.04)),
        ("polyfill over the meridian", _square(-0.02, 10.0, 0.04)),
        ("polyfill over the origin", _square(-0.02, -0.02, 0.04)),
        ("polyfill in the interior", _square(10.0, 10.0, 0.04)),
    ):
        index = itacart.polyfill(polygon, 4, compact=False)
        corpus[label] = [index, *_sample(itacart.decompose(index))]

    # An extension zone: ground the fill once refused entirely.
    west, south, _, _ = itacart.extension_bounds("CHUKOTKA")
    zone = _square(west + 0.01, south + 0.01, 0.04)
    zone_index = itacart.polyfill(zone, 4, compact=False)
    corpus["polyfill inside an extension zone"] = [
        zone_index,
        *_sample(itacart.decompose(zone_index)),
    ]

    # A compacted fill, whose meaning changed after this codec was written.
    compacted = itacart.polyfill(_square(10.0, 10.0, 0.04), 4, compact=True)
    corpus["polyfill compacted"] = [compacted, *_sample(itacart.decompose(compacted))]

    # Row zero, on both sides of the equator.
    corpus["row zero across the equator"] = [
        itacart.compose(["NE(0625/0000)", "SE(0625/0000)"]),
        "NE(0625/0000)",
        "SE(0625/0000)",
    ]

    # Column zero: the meridian triangle, which exists only in the east.
    corpus["the meridian triangle"] = [
        itacart.compose(["NE(0000/0451)", "SE(0000/0451)"]),
        "NE(0000/0451)",
    ]

    # The trapezoid's surplus child, which lands one column past the last
    # column that is a cell.
    trapezoid = "NE(2003/0000)"
    corpus["the trapezoid's children"] = [
        itacart.compose(_flatten(itacart.get_children(trapezoid))),
        "NE(2004/0000(3))",
        trapezoid,
    ]

    # The polar row, whose parent yields more children than the ratio.
    polar = "NE(0001/0999)"
    corpus["the polar row"] = [
        itacart.compose(_flatten(itacart.get_children(polar))),
        polar,
    ]

    return corpus


CORPUS = _build_corpus()


def test_every_corpus_entry_is_populated() -> None:
    """Declare the size of every entry, so a green table cannot hide a zero.

    A bucket that silently emptied is the failure mode this guards: the
    table stays green while measuring nothing.
    """
    sizes = {label: len(entries) for label, entries in CORPUS.items()}
    assert len(sizes) == 11, f"expected eleven entries, got {sorted(sizes)}"
    assert all(count > 0 for count in sizes.values()), sizes
    assert sizes == {
        "compose over several quadrants": 1,
        "polyfill over the equator": 4,
        "polyfill over the meridian": 4,
        "polyfill over the origin": 4,
        "polyfill in the interior": 4,
        "polyfill inside an extension zone": 4,
        "polyfill compacted": 4,
        "row zero across the equator": 3,
        "the meridian triangle": 2,
        "the trapezoid's children": 3,
        "the polar row": 2,
    }


def test_the_corpus_reaches_the_families_it_names() -> None:
    """Each entry contains what its name claims, not merely something."""
    equator = CORPUS["polyfill over the equator"][0]
    assert sorted({cell[:2] for cell in itacart.decompose(equator)}) == ["NE", "SE"]

    meridian = CORPUS["polyfill over the meridian"][0]
    assert sorted({cell[:2] for cell in itacart.decompose(meridian)}) == ["NE", "NW"]

    zone = CORPUS["polyfill inside an extension zone"][0]
    cells = itacart.decompose(zone)
    assert all(itacart.is_extension_cell(cell) for cell in cells)

    assert any(
        entry.startswith("NE(2004/") for entry in CORPUS["the trapezoid's children"]
    )
    assert itacart.is_trapezoidal_cell("NE(0001/0999)")


